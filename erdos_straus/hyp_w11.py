"""W11: for p prime ≡ 1 (24) and a ≡ 3 (4), a ≤ AMAX: the a-step works (exists d | (px)^2, d < px, a | px+d, a | px+(px)^2/d)
iff -1 lies in the subgroup of (Z/a)^* generated by the prime factors of p*x coprime to a (x = (p+a)/4)."""
import csv, sys
from math import gcd
from collections import Counter
CSV=sys.argv[1]; K=int(sys.argv[2]); AMAX=int(sys.argv[3])
ps=[int(r['p']) for r in csv.DictReader(open(CSV))][:K]
def pf(n):
    out=[]; i=2
    while i*i<=n:
        while n%i==0: out.append(i); n//=i
        i+=1
    if n>1: out.append(n)
    return out
def divisors_sq(f):
    ds=[1]
    for q,e in Counter(f).items(): ds=[d*q**k for d in ds for k in range(2*e+1)]
    return ds
def works(p,a):
    x=(p+a)//4; B=p*x
    for d in divisors_sq(pf(x)+[p]):
        if d<B and (B+d)%a==0 and (B+B*B//d)%a==0: return True
    return False
def subgroup(gens,a):
    S={1}; frontier=[1]
    while frontier:
        s=frontier.pop(); 
        for g in gens:
            t=s*g%a
            if t not in S: S.add(t); frontier.append(t)
    return S
def crit(p,a):
    x=(p+a)//4
    gens=[q%a for q in set(pf(x)+[p]) if gcd(q,a)==1]
    return (a-1) in subgroup(gens,a)
mism=Counter(); tot=0; ex={}
for p in ps:
    for a in range(3,AMAX+1,4):
        tot+=1
        w,c=works(p,a),crit(p,a)
        if w!=c:
            key=('works but crit false' if w else 'crit true but fails')+f' a={a}'
            mism[key]+=1; ex.setdefault(key,p)
print('pairs tested',tot,'mismatches',sum(mism.values()))
for k,v in sorted(mism.items(),key=lambda t:-t[1])[:12]: print(' ',k,v,'e.g. p=',ex[k])
